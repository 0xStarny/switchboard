export type Lang = 'fr' | 'en'
const dicts: Record<Lang, Record<Key, string>> = { fr, en }

const initial = (): Lang => {
  try {
    const saved = localStorage.getItem('sb.lang')
    if (saved === 'fr' || saved === 'en') return saved
  } catch {
    /* ignore */
  }
  return navigator.language.toLowerCase().startsWith('fr') ? 'fr' : 'en'
}

export const useLang = create<{ lang: Lang; setLang(l: Lang): void }>((set) => ({
  lang: initial(),
  setLang(lang) {
    try {
      localStorage.setItem('sb.lang', lang)
    } catch {
      /* ignore */
    }
    document.documentElement.lang = lang
    set({ lang })
  },
}))

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s = dicts[lang][key] ?? key
  // "one|many" forms, picked by the {n} variable.
  if (s.includes('|') && vars && typeof vars.n === 'number') s = s.split('|')[vars.n === 1 ? 0 : 1]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

export function useT() {
  const lang = useLang((s) => s.lang)
  return (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars)
}

export const tNow = (key: Key, vars?: Record<string, string | number>) => translate(useLang.getState().lang, key, vars)

/** Map a Telegram error to a sentence people can act on. */
export function explainError(err: unknown): string {
  const raw = String((err as { errorMessage?: string })?.errorMessage ?? (err as Error)?.message ?? err)
  if (/FLOOD/.test(raw)) return tNow('err.FLOOD')
  for (const k of ['PHONE_CODE_INVALID', 'PASSWORD_HASH_INVALID', 'PHONE_NUMBER_INVALID', 'API_ID_INVALID'] as const)
    if (raw.includes(k)) return tNow(`err.${k}`)
  return tNow('err.generic', { msg: raw })
}
